//! `omakeys doctor` and `omakeys udev-rules`: setup checks and the udev rule
//! for every known board.

use std::fs::{self, OpenOptions};
use std::path::Path;
use std::process::Command;

use crate::board::client::{USAGE, USAGE_PAGE};
use crate::board::evdev::list_keyboards;
use crate::board::profile::{boards_dir, load_profiles, select_profile, BoardProfile, BoardSource};
use crate::core::binds::ensure_hyprland_signature;
use crate::core::config::{config_path, AppConfig};
use crate::ipc;

pub const UDEV_RULE_PATH: &str = "/etc/udev/rules.d/50-omakeys.rules";

/// Udev rule that hands each board's hidraw nodes to the `input` group.
/// `TAG+="uaccess"` alone is not enough: it needs an active logind seat at the
/// moment the device appears, which fails when the board is plugged in before
/// login. The group and mode apply on every add.
pub fn udev_rules(profiles: &[BoardProfile]) -> String {
    let mut out = String::from(
        "# Generated by `omakeys udev-rules`: Raw HID access for the overlay.\n\
         # The input group also reads other input devices, so any process running\n\
         # as you can read keystrokes and write to these boards.\n",
    );
    for p in profiles.iter().filter(|p| p.source == BoardSource::RawHid) {
        out.push_str(&format!(
            "# {}\nKERNEL==\"hidraw*\", ATTRS{{idVendor}}==\"{:04x}\", ATTRS{{idProduct}}==\"{:04x}\", \
             GROUP=\"input\", MODE=\"0660\", TAG+=\"uaccess\"\n",
            p.name, p.vid, p.pid
        ));
    }
    out
}

fn report(ok: bool, text: &str) {
    println!("{} {text}", if ok { "ok  " } else { "FAIL" });
}

fn info(text: &str) {
    println!("     {text}");
}

fn on_path(bin: &str) -> bool {
    std::env::var_os("PATH")
        .is_some_and(|paths| std::env::split_paths(&paths).any(|d| d.join(bin).is_file()))
}

fn in_input_group() -> bool {
    Command::new("id").arg("-nG").output().is_ok_and(|o| {
        String::from_utf8_lossy(&o.stdout)
            .split_whitespace()
            .any(|g| g == "input")
    })
}

/// Print every check. Returns false when something needed is broken.
pub fn run() -> bool {
    let mut healthy = true;
    let mut check = |ok: bool, text: &str| {
        report(ok, text);
        healthy &= ok;
    };

    println!("Desktop");
    ensure_hyprland_signature();
    check(
        std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some(),
        "running under Hyprland (cursor dodge needs it)",
    );
    check(
        on_path("omarchy"),
        "`omarchy` command found (keybind layers need it)",
    );
    check(
        on_path("omarchy-shell"),
        "`omarchy-shell` found (settings panel needs it)",
    );
    check(
        Path::new("/dev/uinput").exists()
            && OpenOptions::new().write(true).open("/dev/uinput").is_ok(),
        "/dev/uinput writable (type mode needs it)",
    );

    println!("Config");
    let path = config_path();
    match fs::read_to_string(&path) {
        Ok(text) => match toml::from_str::<AppConfig>(&text) {
            Ok(_) => check(true, &format!("{} parses", path.display())),
            Err(e) => check(false, &format!("{}: {e}", path.display())),
        },
        Err(_) => check(true, "no config.toml, using defaults"),
    }
    let cfg = crate::core::load_config();

    println!("Boards");
    let profiles = load_profiles();
    for p in &profiles {
        match p.source {
            BoardSource::RawHid => {
                info(&format!("profile {} (QMK, {:04x}:{:04x})", p.name, p.vid, p.pid))
            }
            BoardSource::Evdev => info(&format!("profile {} (any keyboard, no layers)", p.name)),
        }
    }
    info(&format!("add your own in {}", boards_dir().display()));
    let mut devices = Vec::new();
    let mut seen = Vec::new();
    if let Ok(api) = hidapi::HidApi::new() {
        for d in api.device_list() {
            if d.usage_page() == USAGE_PAGE && d.usage() == USAGE {
                seen.push((d.vendor_id(), d.product_id()));
                devices.push((
                    d.vendor_id(),
                    d.product_id(),
                    d.product_string().unwrap_or("?").to_string(),
                    d.path().to_owned(),
                ));
            }
        }
    }
    let keyboards = list_keyboards();
    if devices.is_empty() {
        info("no QMK Raw HID keyboard found (fine for laptop or Bluetooth keyboards)");
    }
    for kb in &keyboards {
        let readable = OpenOptions::new().read(true).open(&kb.path).is_ok();
        check(
            readable,
            &format!(
                "keyboard {} ({}){}",
                kb.name,
                kb.bus_name(),
                if readable {
                    ""
                } else {
                    ": cannot read it, join the `input` group and log in again"
                }
            ),
        );
    }
    if devices.is_empty() && keyboards.is_empty() {
        check(false, "no keyboard found at all");
    }
    for (vid, pid, name, path) in &devices {
        let known = profiles.iter().find(|p| p.vid == *vid && p.pid == *pid);
        let opens = hidapi::HidApi::new().is_ok_and(|api| api.open_path(path).is_ok());
        match known {
            Some(p) => check(
                opens,
                &format!(
                    "{name} {vid:04x}:{pid:04x} matches {}{}",
                    p.name,
                    if opens {
                        ""
                    } else {
                        ", but cannot open it (see udev rule below)"
                    }
                ),
            ),
            None => check(
                false,
                &format!(
                    "{name} {vid:04x}:{pid:04x} has no board profile (see README, adding a board)"
                ),
            ),
        }
    }
    if cfg.board == "auto" || !profiles.iter().any(|p| p.name == cfg.board) {
        let first = select_profile(profiles.clone(), "auto", &seen);
        info(&format!(
            "board = \"auto\": the overlay follows the keyboard you type on, starting with {}",
            first.name
        ));
    } else {
        info(&format!("board = {:?}: the overlay always shows this board", cfg.board));
    }

    println!("Access");
    check(
        Path::new(UDEV_RULE_PATH).exists(),
        &format!("udev rule installed at {UDEV_RULE_PATH}"),
    );
    if !Path::new(UDEV_RULE_PATH).exists() {
        info("run: omakeys udev-rules | sudo tee /etc/udev/rules.d/50-omakeys.rules");
    }
    check(
        in_input_group(),
        "user is in the `input` group (log out and in after adding)",
    );

    println!("Daemon");
    check(
        ipc::send_command(ipc::IpcCommand::Ping).is_ok(),
        "overlay daemon answers",
    );
    healthy
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::board::profile::loremipsum36;

    #[test]
    fn udev_rule_lists_every_board() {
        let rules = udev_rules(&[loremipsum36()]);
        assert!(rules.contains("ATTRS{idVendor}==\"5254\", ATTRS{idProduct}==\"0008\""));
        assert!(rules.contains("GROUP=\"input\""));
    }
}
